const usedPools = new Map<string, Set<number>>();

/** يسحب رسالة عشوائية دون تكرارها حتى تُستهلك القائمة كاملة */
export function pickMsg(pool: string[], key: string): string {
  let used = usedPools.get(key);
  if (!used || used.size >= pool.length) {
    used = new Set<number>();
    usedPools.set(key, used);
  }
  let i = Math.floor(Math.random() * pool.length);
  let guard = 0;
  while (used.has(i) && guard++ < 200) i = Math.floor(Math.random() * pool.length);
  used.add(i);
  return pool[i] ?? pool[0] ?? "";
}
